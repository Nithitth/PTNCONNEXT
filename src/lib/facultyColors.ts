const FALLBACK: FacultyColor = { hex: "#9AA0A6", name: "ไม่พบข้อมูล", verify: true };

/** The faculty's colour; campus suffixes like " กำแพงแสน" are ignored. Unknown faculties get neutral grey. */
export function facultyColor(universityId: string, faculty: string): FacultyColor {
  const map = FACULTY_COLORS[universityId] ?? {};
  return map[faculty] ?? map[faculty.replace(/\s+\S+$/, "")] ?? FALLBACK;
}

/** True for very light colours (white, cream) that need an outline to be visible on white. */
export function isLightColor(hex: string): boolean {
  const n = parseInt(hex.slice(1), 16);
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255];
  return 0.2126 * r + 0.7152 * g + 0.0722 * b > 225;
}
